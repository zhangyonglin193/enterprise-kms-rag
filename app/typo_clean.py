# -*- coding: utf-8 -*-
"""OCR 形近错字清洗规则（入库管线 L0 数据卫生层）。

背景：部分源文档是「扫描件→OCR→转 Word」产物，文字层带海量形近错字
（如「透法」代「违法」、「系计」代「累计」、「各付佥」代「备付金」），
导致模型复述时受噪声干扰发生枚举漂移（Q13/Q27 实测 cov≈0.01）。
原图已丢失无法重 OCR，只能在入库时按错字形态清洗文字层。

设计原则（结构签名驱动，零文档特判）：
- 每条规则识别的是 OCR 形近混淆的「形态签名」，不绑定具体文档名；
- 全库 2181 块干跑验证过命中安全性：49 条特异串只命中脏文档、零误杀；
- 高危短串必须带上下文锚定/负向断言（如「与比」锚定「超过」，
  防误杀「西班牙帝国与比索时代」；「道成」锚定「损害/不良」，防「车道成本」）；
- 章节标题粘连用通用正则（法规文档普适），不写死「第十二条」。

挂载点：Indexer.ingest 在 load_structured 之后、分块之前调用 clean_ocr_typos，
受 settings.clean_ocr_typos 开关控制（CLEAN_OCR_TYPOS=0 可关）。

幂等性：对已清洗文本重复调用无副作用（映射「正」串不含「错」串；
正则锚定在替换后不再匹配；负向断言防二次替换）。
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 1) 纯字符串映射：特异串（全库干跑验证只命中脏文档、零误杀），长串在前防子串覆盖
# ---------------------------------------------------------------------------
OCR_TYPO_FIXES: list[tuple[str, str]] = [
    # 评级等级枚举（OCR 丢字/错字）
    ("A（AAAA、A）", "A（AAA、AA、A）"),
    ("B（BBB、B、B）", "B（BBB、BB、B）"),
    ("C类C机构", "C类C级机构"),
    # 金融术语形近错字
    ("金融机支付", "金融机构支付"),
    ("银行卡收业务", "银行卡收单业务"),
    ("客户付金管理", "客户备付金管理"),
    ("各付佥", "备付金"),
    ("各付金银行", "备付金银行"),
    ("条付金", "备付金"),
    ("支付算协会", "支付清算协会"),
    ("分文机构", "分支机构"),
    ("配行业自律管理", "配合行业自律管理"),
    ("配今", "配合"),
    ("通过伪、变造", "通过伪造、变造"),
    # 法律用语形近错字
    ("适法犯", "违法犯"),
    ("透法", "违法"),
    ("迷法", "违法"),
    ("适规", "合规"),
    ("会规", "合规"),
    ("隐惠", "隐患"),
    # 常用字形近错字
    ("系计", "累计"),
    ("（全）", "（含）"),
    ("童事长", "董事长"),
    ("接照", "按照"),
    ("调鏊", "调整"),
    ("或老", "或者"),
    ("（--）", "（一）"),
    ("文持", "支持"),
    ("范图", "范围"),
    ("技露", "披露"),
    ("公词", "公司"),
    ("漏报、报、", "漏报、瞒报、"),
    ("类别、次", "类别、级次"),
    ("（（非银行", "（《非银行"),
    ("并子", "并于"),
    ("异带", "异常"),
    # 排版/标点修正（特异串）
    ("一次3.", "一次。\n3."),
    ("措施外对限期", "措施外，对限期"),
    ("股票挂牌公开转让", "股票、挂牌公开转让"),
    # 全角百分号标准化（普适，多文档命中均为全角％）
    ("％", "%"),
]

# ---------------------------------------------------------------------------
# 2) 正则模式：高危短串带上下文锚定/负向断言（防误杀正常文本），及普适排版规则
#    顺序敏感：「道成」须先于裸「成损害」补「造」执行
# ---------------------------------------------------------------------------
OCR_TYPO_PATTERNS: list[tuple[re.Pattern, str]] = [
    # 「道成」→「造成」：锚定后接「损害/不良」（防「车道成本」「通道成本」）
    (re.compile(r"道成(?=损害|不良)"), "造成"),
    # 「每手」→「每年」：锚定后接「进行」（「每手交易」是期货正常词）
    (re.compile(r"每手(?=进行)"), "每年"),
    # 「三处理」→「且处理」：锚定前逗号（防「再三处理」）
    (re.compile(r"(?<=，)三处理"), "且处理"),
    # 「与比」→「占比」：锚定后接「超过」（防「西班牙帝国与比索时代」）
    (re.compile(r"与比(?=超过)"), "占比"),
    # 「任一形」→「任一情形」：后向断言防「任一情形」二次替换（good 含 bad 的幂等陷阱）
    (re.compile(r"任一形(?!情)"), "任一情形"),
    # 「重大事项降」→「重大事项隐瞒」：锚定后顿号（防「重大事项降低」）
    (re.compile(r"重大事项降(?=、)"), "重大事项隐瞒"),
    # 裸「成损害」补「造」：负向断言防「造成损害」二次替换
    (re.compile(r"(?<!造)成损害"), "造成损害"),
    # Markdown 转义残留：\[2012\] → 〔2012〕（法规年份引用；PDF/MD 转换层把〔〕
    # 转义成 \[ \]，实测 doc20 反电诈报告）。只认「纯数字」内容（全库该形态均为年份），
    # 不碰 \[a-z\] 这类正则字面量与正文方括号
    (re.compile(r"\\\[(\d{1,8})\\\]"), r"〔\1〕"),
    # 编号缺左括号：句末标点后紧跟「X）」补「（」（OCR 丢左括号；普适法规编号）
    (re.compile(r"(?<=[。！？；\n])([一二三四五六七八九十]+）)"), r"（\1"),
    # 章节标题粘连：句末标点后紧跟「第X条/章/节」补换行（法规文档普适）
    (re.compile(r"([。！？])(第[一二三四五六七八九十百零\d]+[条章节])"), r"\1\n\2"),
    # 书名号后章节粘连：》第X章/条/节 补换行
    (re.compile(r"(》)(第[一二三四五六七八九十百零\d]+[章条节])"), r"\1\n\2"),
    # 编号粘连：）或》后紧跟（N）编号补换行
    (re.compile(r"([）》])(（[一二三四五六七八九十]+）)"), r"\1\n\2"),
]


def clean_ocr_typos(text: str) -> str:
    """应用 OCR 形近错字清洗。幂等：对干净文本无副作用。

    顺序：先字符串映射（长串在前），再正则模式（锚定/断言/排版）。
    """
    if not text:
        return text
    t = text
    for bad, good in OCR_TYPO_FIXES:
        if bad in t:
            t = t.replace(bad, good)
    for pat, repl in OCR_TYPO_PATTERNS:
        t = pat.sub(repl, t)
    return t
